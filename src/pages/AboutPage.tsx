import { Layout } from "../components/Layout";
import type { Dataset } from "../lib/types";

export function AboutPage({
  dataset,
  base,
  path,
  repo,
}: {
  dataset: Dataset;
  base: string;
  path: string;
  repo: string | null;
}) {
  const manifest = dataset.manifest;
  const repoName = repo || "ashishkamra/interpretable_benchmark_explorer";
  const blob = (file: string) => `https://github.com/${repoName}/blob/main/${file}`;
  const raw = (file: string) => `https://raw.githubusercontent.com/${repoName}/main/${file}`;
  const runUrl = manifest.run_id ? `https://github.com/${repoName}/actions/runs/${manifest.run_id}` : null;
  const files = ["data/scores.json", "data/models.json", "data/benchmarks.json", "data/refusals.json", "data/manifest.json"];
  return (
    <Layout base={base} path={path}>
      <h1>About</h1>
      <p className="lede">
        This site transcribes published benchmark numbers and keeps the context on the same card as the number. It does
        not re-run evaluations, and it does not blend them into a winner.
      </p>
      <h2>How a score gets here</h2>
      <ul>
        <li>An agent, or a person, sends models and scores to a GitHub Action. The action does not scrape model cards.</li>
        <li>Every primary score needs a source URL, a location on that page, and the configuration the benchmark requires.</li>
        <li>Missing harness, split, or version is stored as missing. It is not filled in, and it cannot be the primary number.</li>
        <li>The primary score is chosen by the sender and checked by the action. The highest number is not chosen automatically.</li>
        <li>Aggregator sites can help someone find a table. They are not a citation unless they ran the evaluation.</li>
        <li>Interpretations are human-written fields. Nothing on a card is generated by a model at read time.</li>
      </ul>
      <h2>Last collection pass</h2>
      <p>
        {manifest.updated_at.slice(0, 10)} · {manifest.note} {manifest.counts.models} models, {manifest.counts.scores}{" "}
        scores, {manifest.counts.benchmarks} benchmarks.
      </p>
      {runUrl ? (
        <p>
          <a href={runUrl}>Refresh run</a>
        </p>
      ) : null}
      <h2>What this site will not claim</h2>
      <ul>
        <li>That one score makes a model smarter, production-ready, or generally better.</li>
        <li>That two numbers are comparable when the harness, split, tools, or version differ.</li>
        <li>That a small gap is meaningful when no editorial threshold is on file. The gap note is omitted instead of invented.</li>
        <li>A sitewide rank, Elo, or weighted index.</li>
      </ul>
      <h2>Sources you can open</h2>
      <p>
        Every score on a card and in a table links to the page the number was read from, plus where on that page to look.
        The dataset itself is public JSON:
      </p>
      <ul>
        {files.map((file) => (
          <li key={file}>
            <a href={blob(file)}>{file}</a> · <a href={raw(file)}>raw</a>
          </li>
        ))}
      </ul>
      <p>
        <a href={blob("Interpretable_Benchmark_Explorer_Design_Doc.md")}>Design document</a>
      </p>
    </Layout>
  );
}
